/** Ориентация молнии: какую линию она убирает при списывании. */
export type LightningOrientation = 'row' | 'col';

/**
 * Молния. Образуется при списывании четырёх в ряд: горизонтальный ряд
 * даёт молнию, убирающую строку, вертикальный — убирающую столбец.
 *
 * При списывании (в том числе в составе совпадения или от взрыва бомбы)
 * молния очищает всю строку или столбец в зависимости от
 * {@link orientation} — с эффектом молнии по линии.
 *
 * Комбо при скрещивании: с бомбой — ряд или колонка шириной 3 клетки
 * по линии молнии; со второй молнией — ряд и колонка от точки скрещения.
 */
export class LightningModel {
  readonly kind = 'lightning' as const;

  constructor(
    /** Цвет, которым молния участвует в совпадениях. */
    readonly color: number,
    /** Линия, которую молния очищает при активации. */
    readonly orientation: LightningOrientation,
  ) {}
}
